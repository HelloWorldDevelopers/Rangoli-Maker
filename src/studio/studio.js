  function bindKeys() {
    addEventListener('keydown', e => {
      if (viewEl().hidden) return;
      const tag = (e.target.tagName || '').toLowerCase();
      if (tag === 'input' || tag === 'select' || tag === 'textarea' || document.querySelector('#view-studio .rm-modal')) return;
      const k = e.key.toLowerCase(), mod = e.ctrlKey || e.metaKey;
      if (mod && k === 'z') { e.preventDefault(); e.shiftKey ? redo() : undo(); return; }
      if (mod && k === 'y') { e.preventDefault(); redo(); return; }
      if (mod && k === 'e') { e.preventDefault(); RM.exporter.studioDialog(viewEl(), doc); return; }
      if (mod && k === 'c') { if (sel.length) { clip = RM.clone(sel); showSel(); e.preventDefault(); } return; }
      if (mod && k === 'v') { if (clip.length) { addCopies(clip, 'h_paste', false); e.preventDefault(); } return; }
      if (mod && k === 'd') { e.preventDefault(); if (sel.length) addCopies(sel, 'h_dup', true); return; }
      if (mod && k === 'a') { e.preventDefault(); sel = active().items.filter(it => it.t !== 'fill' && !it.e); if (P.tool !== 'select') setTool('select'); showSel(); return; }
      if (mod) return;
      if ((k === 'delete' || k === 'backspace') && sel.length) { e.preventDefault(); deleteSel(); return; }
      if (k === 'escape') { clearSel(); return; }
      if (k.startsWith('arrow') && sel.length) { e.preventDefault(); const s = e.shiftKey ? 0.03 : 0.005; nudge(k === 'arrowleft' ? -s : k === 'arrowright' ? s : 0, k === 'arrowup' ? -s : k === 'arrowdown' ? s : 0); return; }
      if (e.code === 'Space') { if (!space) { space = true; $('#sWork').classList.add('panning'); } e.preventDefault(); return; }
      if (KEYTOOL[k]) { setTool(KEYTOOL[k]); return; }
      if (k === 'm') { P.mirror = !P.mirror; savePrefs(); syncControls(); guides(); refreshInfo(); }
      else if (k === 's') { P.snap = !P.snap; savePrefs(); syncControls(); refreshInfo(); }
      else if (k === '[' || k === ']') { P.w = Math.max(1, Math.min(80, P.w + (k === ']' ? 1 : -1) * Math.max(1, Math.round(P.w * 0.15)))); savePrefs(); syncControls(); }
      else if (k === '0') fit();
      else if (k === '\\') togglePanel();
      else if (k === '+' || k === '=') zoomTo(zoomNow() * 1.25);
      else if (k === '-') zoomTo(zoomNow() / 1.25);
      else if (k === '?') help();
    });
    addEventListener('keyup', e => { if (e.code === 'Space') { space = false; $('#sWork').classList.toggle('panning', P.tool === 'pan'); } });
  }

